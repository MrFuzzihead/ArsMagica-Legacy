package am2.mixins;

import java.util.List;
import java.util.Map;
import java.util.Set;

import com.gtnewhorizon.gtnhmixins.IEarlyMixinLoader;
import com.gtnewhorizon.gtnhmixins.builders.IMixins;

import cpw.mods.fml.relauncher.IFMLLoadingPlugin;

/**
 * Early Mixin entry point.
 *
 * <p>
 * This replaces the old {@code net.tclproject.mysteriumlib} ASM coremod, which was never registered in the produced
 * jar (see CODE_REVIEW.md section 2.1). The class name is wired through {@code coreModClass} in
 * {@code gradle.properties}; the Mixin/GTNHMixins toolchain writes it into the jar manifest as {@code FMLCorePlugin}.
 * </p>
 */
@IFMLLoadingPlugin.MCVersion("1.7.10")
public class EarlyMixinsLoader implements IFMLLoadingPlugin, IEarlyMixinLoader {

    @Override
    public String[] getASMTransformerClass() {
        return new String[0];
    }

    @Override
    public String getModContainerClass() {
        return null;
    }

    @Override
    public String getSetupClass() {
        return null;
    }

    @Override
    public void injectData(Map<String, Object> data) {}

    @Override
    public String getAccessTransformerClass() {
        return null;
    }

    @Override
    public String getMixinConfig() {
        return "mixins.arsmagica2.early.json";
    }

    @Override
    public List<String> getMixins(Set<String> loadedCoreMods) {
        return IMixins.getEarlyMixins(Mixins.class, loadedCoreMods);
    }
}
